-- unaccent() não é IMMUTABLE; este invólucro permite usá-lo em coluna gerada e índice.
create or replace function f_unaccent(text) returns text
  language sql immutable parallel safe strict
  as $$ select public.unaccent('public.unaccent'::regdictionary, $1) $$;

create table if not exists food_sources (
  id            integer generated by default as identity primary key,
  code          text not null unique,               -- TACO, TBCA, CUSTOM
  name          text not null,
  version       text,
  citation      text,
  license_notes text
);

create table if not exists nutrients (
  id       integer generated by default as identity primary key,
  code     text not null unique,                    -- energy_kcal, protein_g, ...
  name     text not null,
  unit     text not null,                           -- kcal, kJ, g, mg, mcg, %
  position integer not null default 0
);

create table if not exists foods (
  id                 integer generated by default as identity primary key,
  source_id          integer not null references food_sources (id),
  source_code        text,                          -- código do alimento na fonte (TACO: 1..597)
  organization_id    uuid,                          -- nulo = base pública; FK entra com a tabela organizations (RN-004)
  name               text not null,
  food_group         text,
  household_measures jsonb not null default '[]'::jsonb,  -- [{"label": "colher de sopa", "grams": 25}]
  search_name        text generated always as (lower(f_unaccent(name))) stored,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz,
  constraint foods_source_code_unique unique (source_id, source_code)
);

create index if not exists foods_search_name_trgm on foods using gin (search_name gin_trgm_ops);
create index if not exists foods_organization_id on foods (organization_id);

create table if not exists food_nutrients (
  id              integer generated by default as identity primary key,
  food_id         integer not null references foods (id) on delete cascade,
  nutrient_id     integer not null references nutrients (id),
  amount_per_100g numeric(12, 4),                   -- null = não analisado (NA)
  is_trace        boolean not null default false,   -- "Tr" na TACO: gravado como 0
  constraint food_nutrients_unique unique (food_id, nutrient_id)
);

create index if not exists food_nutrients_nutrient_id on food_nutrients (nutrient_id);

