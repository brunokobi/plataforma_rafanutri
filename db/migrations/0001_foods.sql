-- Busca sem acento e tolerante a erro de digitação.
-- Prioridade: base da própria organização, depois TACO, depois as demais; dentro disso,
-- quem contém todas as palavras da busca e tem maior semelhança vem antes.
create or replace function search_foods(query text, org_id uuid default null, lim integer default 20)
returns table (id integer, name text, food_group text, source text, score real)
language sql stable parallel safe
as $$
  with q as (select lower(f_unaccent(trim(query))) as t)
  select f.id, f.name, f.food_group, s.code as source,
         (similarity(f.search_name, q.t)
          + case when f.search_name like q.t || '%' then 0.5 else 0 end
          + case when (select bool_and(f.search_name like '%' || w || '%')
                       from unnest(string_to_array(q.t, ' ')) w where w <> '') then 0.5 else 0 end
         )::real as score
  from foods f
  join food_sources s on s.id = f.source_id
  cross join q
  where (f.organization_id is null or f.organization_id = org_id)
    and length(q.t) > 0
    and (f.search_name % q.t
         or (select bool_and(f.search_name like '%' || w || '%')
             from unnest(string_to_array(q.t, ' ')) w where w <> ''))
  order by (f.organization_id is not null and f.organization_id = org_id) desc,
           (s.code = 'TACO') desc,
           score desc,
           f.name
  limit greatest(1, least(lim, 100));
$$;

